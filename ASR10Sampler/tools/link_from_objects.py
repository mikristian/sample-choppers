#!/usr/bin/env python3
"""Re-link an existing JUCE CMake target from its compiled object files.

This is a low-free-disk-space fallback for the already configured project.
It uses the exact compile/link arguments generated by CMake, but substitutes
the shared-code object list for the large intermediate static library.
Run from this ASR10Sampler project after changed source files compile.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import shlex
import subprocess

PROJECT = Path(__file__).resolve().parents[1]
BUILD = PROJECT / "build"
TARGETS = {
    "Standalone": (
        "ASR10SamplerLab_Standalone",
        "ASR10SamplerLab_artefacts/Release/Standalone/ASR-10 Sampler Lab.app",
    ),
    "AU": (
        "ASR10SamplerLab_AU",
        "ASR10SamplerLab_artefacts/Release/AU/ASR-10 Sampler Lab.component",
    ),
    "VST3": (
        "ASR10SamplerLab_VST3",
        "ASR10SamplerLab_artefacts/Release/VST3/ASR-10 Sampler Lab.vst3",
    ),
}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("formats", nargs="+", choices=TARGETS)
    args = parser.parse_args()
    generated = BUILD / "CMakeFiles/ASR10SamplerLab.dir/link.txt"
    if not generated.exists():
        parser.error("CMake build/link files missing; run a regular configure first")
    commands = generated.read_text().splitlines()
    ar_command = shlex.split(commands[0])
    objects = [arg for arg in ar_command if arg.endswith(".o")]
    if len(objects) < 10:
        parser.error("too few shared-code objects to link")
    for obj in objects:
        if not (BUILD / obj).is_file():
            parser.error(f"missing compiled shared object: {obj}")

    for fmt in args.formats:
        target, bundle = TARGETS[fmt]
        path = BUILD / f"CMakeFiles/{target}.dir/link.txt"
        argv = shlex.split(path.read_text())
        library_pos = next(
            (i for i, arg in enumerate(argv) if arg.endswith("_SharedCode.a")), None
        )
        if library_pos is None:
            parser.error(f"{fmt}: static library not found in linker arguments")
        argv[library_pos : library_pos + 1] = objects
        output_index = argv.index("-o") + 1
        output = BUILD / argv[output_index]
        temporary = output.with_name(output.name + ".new")
        if temporary.exists():
            temporary.unlink()
        argv[output_index] = str(temporary)
        print(f"LINK {fmt}: {len(objects)} shared objects", flush=True)
        try:
            subprocess.run(argv, cwd=BUILD, check=True)
            if not temporary.is_file() or temporary.stat().st_size < 1024 * 1024:
                raise RuntimeError(f"{fmt}: missing/truncated linked output")
            os.replace(temporary, output)
            bundle_path = BUILD / bundle
            subprocess.run(
                ["codesign", "--force", "--deep", "--sign", "-", str(bundle_path)],
                check=True,
            )
            subprocess.run(
                ["codesign", "--verify", "--deep", "--strict", str(bundle_path)],
                check=True,
            )
            print(f"PASS {fmt}: {output}", flush=True)
        finally:
            if temporary.exists():
                temporary.unlink()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
